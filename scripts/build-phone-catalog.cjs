// Regenerate src/lib/phone/countries.ts from Google libphonenumber metadata (via libphonenumber-js, MIT).
// Run: npm i libphonenumber-js in a temp dir, then NODE_PATH=<tmp>/node_modules node scripts/build-phone-catalog.cjs
const fs = require("fs");
const m = require("libphonenumber-js/metadata.min.json");
const v = require("libphonenumber-js/package.json").version;
const rows = Object.entries(m.countries).filter(([iso]) => /^[A-Z]{2}$/.test(iso))
  .map(([iso, c]) => [iso, c[0], Array.isArray(c[3]) ? c[3].filter((x) => typeof x === "number") : [], c[2] ? 1 : 0]);
// mainCountryForCode: libphonenumber marks the main country first in country_calling_codes
const main = {}; for (const [code, list] of Object.entries(m.country_calling_codes)) main[code] = list[0];
const out = `/* Generated by scripts/build-phone-catalog.cjs from libphonenumber-js ${v} metadata (Google libphonenumber, MIT/Apache-2.0).
   Row: [ISO 3166-1 alpha-2, calling code, possible national lengths]. Do not edit by hand. */
export const PHONE_COUNTRIES: ReadonlyArray<readonly [string, string, readonly number[]]> = ${JSON.stringify(rows.map(r => [r[0], r[1], r[2]]))};
/** Main country for shared calling codes (e.g. +1 → US, +7 → RU, +44 → GB). */
export const MAIN_FOR_CODE: Readonly<Record<string, string>> = ${JSON.stringify(main)};
`;
fs.writeFileSync(__dirname + "/../src/lib/phone/countries.ts", out);
console.log(rows.length, "countries");
